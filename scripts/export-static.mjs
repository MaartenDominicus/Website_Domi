import { cp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { notFoundDocument } from "./not-found-export.mjs";

const projectRoot = process.cwd();
const buildRoot = join(projectRoot, "dist");
const outputRoot = join(projectRoot, "out");
const workerPath = join(buildRoot, "server", "index.js");
const legacyTargets = JSON.parse(await readFile(join(projectRoot, "app", "legacy-redirects.json"), "utf8"));

const projectSlugs = [
  "badkamer-toilet-amsterdam",
  "complete-renovatie-amsterdam",
  "complete-renovatie-rotterdam",
  "tuinhuis-amsterdam",
  "riolering-apeldoorn",
  "vloerverwarming-kampen",
];

const knowledgeSlugs = [
  "veilige-elektrische-installatie",
  "binnendeuren-hang-en-sluitwerk",
  "tegels-en-voegen-kiezen",
  "verborgen-waterlek-opsporen",
  "warmwatertoestel-kiezen",
  "signalen-elektrische-problemen",
  "badkamerventilator-kiezen",
  "leidingnoodgeval-eerste-stappen",
];

const routes = [
  "/",
  "/en",
  "/privacy",
  "/voorwaarden",
  "/diensten/woningrenovatie",
  "/diensten/badkamerrenovatie",
  "/diensten/elektra-verlichting",
  "/diensten/water-sanitair",
  "/diensten/vloerverwarming",
  "/diensten/timmerwerk-montage",
  "/diensten/tegel-stuc-schilderwerk",
  ...projectSlugs.flatMap((slug) => [`/projecten/${slug}`, `/en/projects/${slug}`]),
  ...knowledgeSlugs.flatMap((slug) => [`/kennis/${slug}`, `/en/insights/${slug}`]),
];

await rm(outputRoot, { recursive: true, force: true });
await mkdir(outputRoot, { recursive: true });
await cp(join(buildRoot, "client"), outputRoot, { recursive: true });
await writeFile(join(outputRoot, ".nojekyll"), "");

try {
  const domain = (await readFile(join(projectRoot, "CNAME"), "utf8")).trim();
  if (domain) await writeFile(join(outputRoot, "CNAME"), `${domain}\n`);
} catch (error) {
  if (error?.code !== "ENOENT") throw error;
}

const { default: worker } = await import(`${pathToFileURL(workerPath).href}?static-export=${Date.now()}`);
const platform = {
  ASSETS: { fetch: async () => new Response("Not found", { status: 404 }) },
};
const executionContext = { waitUntil() {}, passThroughOnException() {} };

async function render(route) {
  const response = await worker.fetch(
    // Static files must include async route metadata in the head for crawlers
    // that do not execute JavaScript. Use the renderer's blocking bot mode.
    new Request(`https://www.matrisbouw.nl${route}`, { headers: { accept: "text/html", "user-agent": "Twitterbot" } }),
    platform,
    executionContext,
  );
  const contentType = response.headers.get("content-type") ?? "";
  if (response.status !== 200 || !contentType.startsWith("text/html")) {
    throw new Error(`Static export failed for ${route}: ${response.status} ${contentType}`);
  }
  let html = await response.text();
  if (route === "/en" || route.startsWith("/en/")) {
    const englishHtml = html.replace(/<html\b([^>]*?)\blang="nl"/i, '<html$1lang="en"');
    if (englishHtml === html) throw new Error(`English route ${route} has no Dutch root language to replace`);
    html = englishHtml;
  }
  const outputPath = route === "/" ? join(outputRoot, "index.html") : join(outputRoot, route.slice(1), "index.html");
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, html);
}

for (const route of routes) await render(route);

// GitHub Pages cannot send HTTP redirects. Immediate HTML refreshes and visible
// links preserve the same destinations without requiring JavaScript. Nginx
// uses the generated include below to send permanent HTTP redirects instead.
const nginxRedirects = ["# Generated by export-static.mjs from app/legacy-redirects.json."];
const homeHtml = await readFile(join(outputRoot, "index.html"), "utf8");
for (const [slug, fragment] of Object.entries(legacyTargets)) {
  if (!/^[a-z][a-z0-9-]*(?:\.html)?$/.test(slug) || !/^#[a-z][a-z0-9-]*$/.test(fragment)) {
    throw new Error(`Invalid legacy redirect: ${slug} -> ${fragment}`);
  }
  if (!homeHtml.includes(`id="${fragment.slice(1)}"`)) {
    throw new Error(`Missing legacy redirect destination: ${fragment}`);
  }
  const target = `/${fragment}`;
  const html = `<!doctype html><html lang="nl"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>Pagina verplaatst | Domi Installatie</title><link rel="canonical" href="https://www.matrisbouw.nl/"><meta http-equiv="refresh" content="0;url=${target}"></head><body><main><h1>Deze pagina is verplaatst</h1><p><a href="${target}">Ga naar Domi Installatie</a></p></main></body></html>\n`;
  const outputPath = slug.endsWith(".html") ? join(outputRoot, slug) : join(outputRoot, slug, "index.html");
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, html);
  const paths = slug.endsWith(".html") ? [`/${slug}`] : [`/${slug}`, `/${slug}/`];
  for (const path of paths) {
    nginxRedirects.push(`location = ${path} { return 308 "${target}"; }`);
  }
}
await writeFile(join(buildRoot, "legacy-redirects.conf"), `${nginxRedirects.join("\n")}\n`);


for (const route of ["/robots.txt", "/sitemap.xml"]) {
  const response = await worker.fetch(
    new Request(`https://www.matrisbouw.nl${route}`),
    platform,
    executionContext,
  );
  if (response.status !== 200) {
    throw new Error(`Static export failed for ${route}: ${response.status}`);
  }
  await writeFile(join(outputRoot, route.slice(1)), await response.text());
}

const notFoundResponse = await worker.fetch(
  new Request("https://www.matrisbouw.nl/__static-export-not-found__", { headers: { accept: "text/html" } }),
  platform,
  executionContext,
);
await writeFile(join(outputRoot, "404.html"), await notFoundDocument(notFoundResponse));

console.log(`Exported ${routes.length} routes to ${outputRoot}`);
